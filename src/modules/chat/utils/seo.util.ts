// utils/seo.util.ts
import { prisma } from "../../../config/prisma";

const SITE_NAME = process.env.SITE_NAME || "FinixMart";
const SITE_URL = process.env.SITE_URL || "https://example.com";

function truncate(text: string, max: number): string {
  if (!text) return "";
  if (text.length <= max) return text;
  return text.slice(0, max - 1).trimEnd() + "…";
}

function stripHtml(text: string): string {
  return text.replace(/<[^>]*>/g, " ").replace(/\s+/g, " ").trim();
}

/**
 * Builds the full SEO payload for a product. Pure function — takes plain
 * data, returns plain data. Called by:
 *   1. generateAndSaveProductSEO() below (on approval / update)
 *   2. the product-details read path, to build JSON-LD at request time
 */
export function buildProductSeoPayload(product: {
  id: string;
  name: string;
  nameBn?: string | null;
  slug: string;
  description?: string | null;
  images: { url: string }[];
  category?: { name: string; slug: string } | null;
  brand?: { name: string } | null;
  vendor?: { storeName: string } | null;
  variants: { price: any; specialPrice?: any; sku: string }[];
}) {
  const cleanDescription = stripHtml(product.description || "");
  const price = product.variants[0]?.price ?? 0;
  const brandName = product.brand?.name;

  const metaTitle = truncate(
    `${product.name}${brandName ? ` | ${brandName}` : ""} - ${SITE_NAME}`,
    60
  );
  const metaDescription = truncate(
    cleanDescription || `Buy ${product.name} online at ${SITE_NAME}. Best price, fast delivery.`,
    160
  );

  const canonicalUrl = `${SITE_URL}/product/${product.slug}`;
  const ogImage = product.images[0]?.url;

  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "Product",
    name: product.name,
    image: product.images.map((i) => i.url),
    description: cleanDescription,
    sku: product.variants[0]?.sku,
    brand: brandName ? { "@type": "Brand", name: brandName } : undefined,
    offers: {
      "@type": "Offer",
      url: canonicalUrl,
      priceCurrency: "BDT",
      price,
      availability: "https://schema.org/InStock",
      seller: product.vendor ? { "@type": "Organization", name: product.vendor.storeName } : undefined,
    },
  };

  const breadcrumb = {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [
      { "@type": "ListItem", position: 1, name: "Home", item: SITE_URL },
      ...(product.category
        ? [
            {
              "@type": "ListItem",
              position: 2,
              name: product.category.name,
              item: `${SITE_URL}/category/${product.category.slug}`,
            },
          ]
        : []),
      { "@type": "ListItem", position: 3, name: product.name, item: canonicalUrl },
    ],
  };

  return {
    metaTitle,
    metaDescription,
    canonicalUrl,
    robots: "INDEX_FOLLOW" as const,
    ogTitle: metaTitle,
    ogDescription: metaDescription,
    ogImage,
    ogType: "PRODUCT" as const,
    twitterTitle: metaTitle,
    twitterDescription: metaDescription,
    twitterImage: ogImage,
    twitterCard: "SUMMARY_LARGE_IMAGE" as const,
    schemaOverride: { jsonLd, breadcrumb },
    sitemapPriority: 0.8,
    sitemapChangefreq: "WEEKLY" as const,
  };
}

/**
 * Fetches the minimal product data needed for SEO generation, builds the
 * payload, and upserts ProductSEO. This is THE single entry point that
 * should be called whenever SEO needs (re)generating.
 *
 * trigger: "APPROVAL" | "MANUAL" | "UPDATE"
 *
 * Business rule from the brief: SEO is auto-generated when an admin
 * approves a product. It is also refreshed automatically if the vendor
 * later edits name/slug/description on an already-approved product, UNLESS
 * an admin/vendor has manually overridden the SEO fields (isAutoGenerated
 * = false), in which case we leave their manual edits alone.
 */
export async function generateAndSaveProductSEO(
  productId: string,
  trigger: "APPROVAL" | "MANUAL" | "UPDATE" = "APPROVAL"
) {
  const product = await prisma.product.findUnique({
    where: { id: productId },
    select: {
      id: true,
      name: true,
      nameBn: true,
      slug: true,
      description: true,
      images: { select: { url: true }, orderBy: { sortOrder: "asc" }, take: 5 },
      category: { select: { name: true, slug: true } },
      brand: { select: { name: true } },
      vendor: { select: { storeName: true } },
      variants: { select: { price: true, specialPrice: true, sku: true }, take: 1 },
      seo: { select: { isAutoGenerated: true } },
    },
  });

  if (!product) throw new Error("Product not found");

  // Respect a manual override — never silently clobber human-edited SEO.
  if (product.seo && product.seo.isAutoGenerated === false && trigger !== "MANUAL") {
    return prisma.productSEO.findUnique({ where: { productId } });
  }

  const payload = buildProductSeoPayload(product as any);

  return prisma.productSEO.upsert({
    where: { productId },
    update: {
      ...payload,
      isPublished: true,
      publishedAt: new Date(),
      isAutoGenerated: trigger !== "MANUAL",
      generatedAt: new Date(),
      generatedTrigger: trigger,
    },
    create: {
      productId,
      ...payload,
      isPublished: true,
      publishedAt: new Date(),
      isAutoGenerated: trigger !== "MANUAL",
      generatedAt: new Date(),
      generatedTrigger: trigger,
    },
  });
}